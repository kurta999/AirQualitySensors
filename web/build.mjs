import { build, transform } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { gzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(fileURLToPath(import.meta.url));
const dist = path.join(root, 'dist');
await mkdir(dist, { recursive: true });
const js = await build({ entryPoints: [path.join(root, 'src/main.ts')], bundle: true,
  minify: true, target: 'es2022', format: 'iife', legalComments: 'eof', write: false });
const css = await transform(await readFile(path.join(root, 'src/style.css'), 'utf8'), { loader: 'css', minify: true });
const files = [
  { path: '/', file: 'index.html', type: 'text/html; charset=utf-8', bytes: await readFile(path.join(root, 'src/index.html')) },
  { path: '/app.js', file: 'app.js', type: 'text/javascript; charset=utf-8', bytes: Buffer.from(js.outputFiles[0].contents) },
  { path: '/style.css', file: 'style.css', type: 'text/css; charset=utf-8', bytes: Buffer.from(css.code) },
  { path: '/licenses.txt', file: 'licenses.txt', type: 'text/plain; charset=utf-8', bytes: await readFile(path.join(root, 'THIRD_PARTY_LICENSES.txt')) }
];
let total = 0;
const source = ['/* Generated by web/build.mjs. Do not edit. Compressed assets stay in flash. */', '#include "web_assets.h"'];
const manifest = [];
for (const [i, file] of files.entries()) {
  const gz = gzipSync(file.bytes, { level: 9, mtime: 0 });
  total += gz.length;
  await writeFile(path.join(dist, file.file), file.bytes);
  await writeFile(path.join(dist, `${file.file}.gz`), gz);
  const rows = Array.from({ length: Math.ceil(gz.length / 24) }, (_, n) =>
    '    ' + [...gz.subarray(n * 24, n * 24 + 24)].map(b => `0x${b.toString(16).padStart(2, '0')}`).join(',') + ',');
  source.push(`static const uint8_t asset_${i}[] = {\n${rows.join('\n')}\n};`);
  manifest.push({ path: file.path, raw: file.bytes.length, gzip: gz.length,
    sha256: createHash('sha256').update(gz).digest('hex') });
}
// A hard budget catches accidental libraries/fonts or framework growth.
if (total > 110 * 1024) throw new Error(`Dashboard gzip size ${total} exceeds 110 KiB budget`);
source.push('const WebAsset web_assets[] = {', ...files.map((f, i) =>
  `    {"${f.path}", "${f.type}", asset_${i}, sizeof(asset_${i})},`), '};',
  'const size_t web_asset_count = sizeof(web_assets) / sizeof(web_assets[0]);', '');
await writeFile(path.join(root, '../Core/Src/web_assets.c'), source.join('\n'));
await writeFile(path.join(dist, 'manifest.json'), JSON.stringify({ total_gzip: total, files: manifest }, null, 2) + '\n');
console.log(`Embedded dashboard: ${total.toLocaleString()} gzip bytes (budget 112,640).`);
console.table(manifest.map(({ path, raw, gzip }) => ({ path, raw, gzip })));
